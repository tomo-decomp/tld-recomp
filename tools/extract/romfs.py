#!/usr/bin/env python3
"""Extract the RomFS of your own copy of the game, with the update applied, into the
`private/tld/` tree the rest of the project expects.

    python3 tools/extract/romfs.py                       # base + update -> private/tld/romfs
    python3 tools/extract/romfs.py --list                # the file table only
    python3 tools/extract/romfs.py --decompress-zs       # also unpack every .zs (Zstandard)
    python3 tools/extract/romfs.py --base X.xci --update Y.nsp --root private/tld

Layout (the same idea as TLDRecomp's `private/tld/`, one game per folder):

    private/tld/exefs/          ExeFS of the version you will run
    private/tld/exefs_update/   ExeFS of the update, when it differs
    private/tld/romfs/          the RomFS data set, update applied
    private/tld/romfs_zs/       the unpacked .zs files (with --decompress-zs)
    private/tld/elf/            main.elf, for the disassembler and the lifter
    private/tld/gen/            code generated by tools/recomp
    private/tld/logs/
    private/tld/manifest.json   what was built, from which packages, with hashes

The extraction is resumable: a file is skipped when its size already matches, and each
file is written to `<name>.part` and renamed, so an interrupted run leaves nothing that
looks complete.
"""
import argparse
import hashlib
import json
import os
import shutil
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import romfs_extract as rx  # noqa: E402

SUBDIRS = ('exefs', 'exefs_update', 'romfs', 'romfs_zs', 'elf', 'gen', 'logs')


def make_layout(root):
    """Create the private tree. Returns {name: path}."""
    paths = {'root': root}
    for name in SUBDIRS:
        p = os.path.join(root, name)
        os.makedirs(p, exist_ok=True)
        paths[name] = p
    return paths


def sha256_of(path, chunk=8 << 20):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        while True:
            b = f.read(chunk)
            if not b:
                break
            h.update(b)
    return h.hexdigest()


def decompress_zs_folder(src_dir, dst_dir, skip_existing=True):
    """Unpack every *.zs (a bare Zstandard frame) into dst_dir, keeping the name minus .zs."""
    try:
        import zstandard
    except ImportError:
        sys.exit('--decompress-zs needs zstandard: pip install zstandard')
    os.makedirs(dst_dir, exist_ok=True)
    targets = []
    for dirpath, _, files in os.walk(src_dir):
        for name in files:
            if name.endswith('.zs'):
                targets.append(os.path.join(dirpath, name))
    print('unpacking %d .zs file(s) -> %s' % (len(targets), dst_dir))
    dctx = zstandard.ZstdDecompressor()
    done = skipped = failed = 0
    t0 = time.time()
    total_bytes = 0
    for src in sorted(targets):
        rel = os.path.relpath(src, src_dir)[:-3]
        dst = os.path.join(dst_dir, rel)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        if skip_existing and os.path.isfile(dst):
            skipped += 1
            continue
        try:
            with open(src, 'rb') as fi, open(dst + '.part', 'wb') as fo:
                dctx.copy_stream(fi, fo)
            os.replace(dst + '.part', dst)
            total_bytes += os.path.getsize(dst)
            done += 1
        except Exception as e:  # a truncated or non-zstd file: report and continue
            failed += 1
            print('  skipped %s: %s' % (rel, e))
        if done % 2000 == 0:
            print('  %d/%d  %.1f GB  %.0f MB/s'
                  % (done, len(targets), total_bytes / 2 ** 30,
                     total_bytes / 2 ** 20 / max(time.time() - t0, 0.01)), flush=True)
    print('unpacked %d, skipped %d, failed %d, %.2f GB in %.0f s'
          % (done, skipped, failed, total_bytes / 2 ** 30, time.time() - t0))
    return done, failed


def write_manifest(paths, base_path, update_path, base, update, entries):
    m = {
        'game': 'Tomodachi Life: Living the Dream',
        'base': {'package': os.path.basename(base_path), 'title_id': '%016X' % base.title_id,
                 'program_nca': base.name, 'version': rx.meta_version(rx.open_package(base_path))[1]},
        'update': None,
        'romfs': {'files': len(entries), 'bytes': sum(e[2] for e in entries)},
        'exefs': {},
    }
    if update is not None:
        m['update'] = {'package': os.path.basename(update_path), 'title_id': '%016X' % update.title_id,
                       'program_nca': update.name,
                       'version': rx.meta_version(rx.open_package(update_path))[1]}
    for sub, name in (('exefs', 'exefs'), ('exefs_update', 'exefs_update')):
        main = os.path.join(paths[sub], 'main')
        if os.path.isfile(main):
            m['exefs'][name] = {'main_bytes': os.path.getsize(main), 'main_sha256': sha256_of(main)}
    with open(os.path.join(paths['root'], 'manifest.json'), 'w') as f:
        json.dump(m, f, indent=2)
        f.write('\n')
    return m


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--root', default=os.path.join(rx._repo_root() or '.', 'tld-recomp', 'private', 'tld'))
    p.add_argument('--base', default=None)
    p.add_argument('--update', default=None)
    p.add_argument('--list', action='store_true')
    p.add_argument('--decompress-zs', action='store_true')
    p.add_argument('--no-romfs', action='store_true')
    a = p.parse_args(argv)

    root = rx._repo_root() or '.'
    base_path = a.base or os.path.join(root, 'roms', 'switch', 'base', 'tomo', 'tomodachi.xci')
    if a.update is None:
        d = os.path.join(root, 'roms', 'switch', 'updates', 'tomo')
        a.update = next((os.path.join(d, n) for n in sorted(os.listdir(d))
                         if n.lower().endswith('.nsp')), None) if os.path.isdir(d) else None

    paths = make_layout(a.root)
    print('layout           %s' % a.root)
    base_pkg, up_pkg = rx.open_package(base_path), (rx.open_package(a.update) if a.update else None)
    base = rx.Nca(base_pkg)
    update = rx.Nca(up_pkg) if up_pkg else None
    if update is not None and base.is_patch() and not update.is_patch():
        base, update = update, base
    print('base             %016X  %s' % (rx.meta_version(base_pkg)[0], os.path.basename(base_path)))
    if update is not None:
        print('update           %016X  v%d  %s' % (rx.meta_version(up_pkg)[0],
                                                   rx.meta_version(up_pkg)[1] or 0,
                                                   os.path.basename(a.update)))

    entries = []
    if not a.no_romfs:
        entries = rx.extract(base, update, paths['romfs'], list_only=a.list)
        if a.list:
            print('(listed only; nothing written)')
        write_manifest(paths, base_path, a.update, base, update, entries)
        print('manifest         %s' % os.path.join(a.root, 'manifest.json'))

    if a.decompress_zs and not a.list and entries:
        decompress_zs_folder(paths['romfs'], paths['romfs_zs'])
    return 0


if __name__ == '__main__':
    sys.exit(main())
